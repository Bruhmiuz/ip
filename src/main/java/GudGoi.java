import java.nio.file.Path;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.time.format.ResolverStyle;
import java.util.ArrayList;

/**
 * The chatbot itself: it holds the task list and carries out commands.
 * <p>
 * It no longer talks to the user, and no longer touches the disk. {@link Ui}
 * and {@link Storage} do those, and this class asks them. Command parsing and
 * the list itself are still here, and {@code A-MoreOOP} moves each of them out
 * in turn.
 */
public class GudGoi {
    // ---------------------------------------------------------------------
    // AI-ASSISTED CODE — CITATION
    // Much of this class was generated by Claude (Anthropic), used through
    // Claude Code, on 2026-08-20 and 2026-08-21, from the Level-2 to Level-5
    // requirements: tasks, listTasks, mark, unmark, addAndConfirm, addTodo,
    // addDeadline, addEvent, and the command dispatch in main. DIVIDER, say and
    // the three printing methods were generated the same way and have since
    // moved to Ui. I reviewed the code before committing it, and rewrote parts
    // of it myself.
    // ---------------------------------------------------------------------

    // ---------------------------------------------------------------------
    // AI-ASSISTED CODE — CITATION
    // The two INPUT_ formatters, DEADLINE_DEFAULT_TIME, EVENT_END_DEFAULT_TIME
    // and parseDateTime were generated by Claude (Anthropic), used through
    // Claude Code, on 2026-08-27, from my specification for Level-8: accept a
    // date on its own or a date with a time, and store both as a date and
    // time. I reviewed the code before committing it.
    // ---------------------------------------------------------------------

    /**
     * The pattern the user types when a time is given, for example
     * {@code 2019-10-15 1800}.
     * <p>
     * {@code uuuu} with {@link ResolverStyle#STRICT} is what makes an
     * impossible date such as {@code 2019-02-30} an error. The lenient default
     * would quietly move it to the end of the month.
     */
    private static final DateTimeFormatter INPUT_WITH_TIME =
            DateTimeFormatter.ofPattern("uuuu-MM-dd HHmm")
            .withResolverStyle(ResolverStyle.STRICT);

    /**
     * The pattern the user types when only a date is given, for example
     * {@code 2019-10-15}.
     */
    private static final DateTimeFormatter INPUT_DATE_ONLY =
            DateTimeFormatter.ofPattern("uuuu-MM-dd")
            .withResolverStyle(ResolverStyle.STRICT);

    /** The time a deadline gets when the user gives only a date. */
    private static final LocalTime DEADLINE_DEFAULT_TIME = LocalTime.of(0, 0);

    /**
     * The time an event's end gets when the user gives only a date, so that a
     * whole-day event runs to the end of that day rather than to its start.
     */
    private static final LocalTime EVENT_END_DEFAULT_TIME = LocalTime.of(23, 59);

    /**
     * The one way in and out for anything the user sees or types.
     * <p>
     * It is {@code static} only because this class still is. It becomes an
     * ordinary field when the class gains a constructor.
     */
    private static final Ui ui = new Ui();

    /**
     * The agenda on disk. Like {@link #ui} it is {@code static} only because
     * this class still is.
     * <p>
     * The path is built from its parts, so the separator is the host system's
     * own and the same line works on Windows and on Linux.
     */
    private static final Storage storage = new Storage(Path.of("data", "saved.txt"));

    /**
     * Tasks entered so far, in the order they were added.
     * {@link Storage} writes the list out whenever it changes, and gives it
     * back when the program starts.
     */
    private static final ArrayList<Task> tasks = new ArrayList<>();

    /**
     * Reads a date, or a date and a time, from what the user typed.
     * <p>
     * The pattern with a time is tried first. A date on its own is not an
     * error: it takes {@code defaultTime}, which is how a deadline gets
     * midnight while an event's end gets the last minute of the day. The
     * caller supplies that default, because only the caller knows which end of
     * a day it wants.
     * <p>
     * This lives here for now because there is no class yet whose job is to
     * make sense of a command. {@code A-MoreOOP} names that class.
     *
     * @param text what the user wrote after {@code /by}, {@code /from} or
     *             {@code /to}
     * @param defaultTime the time to use when the text carries none
     * @return the point in time the text names
     * @throws DateFormatException if the text is neither pattern
     */
    private static LocalDateTime parseDateTime(String text, LocalTime defaultTime)
            throws DateFormatException {
        // Runs of blanks between the date and the time are collapsed, so that
        // a stray extra space is not an error the user has to hunt for.
        String trimmed = text.trim().replaceAll("\\s+", " ");
        try {
            return LocalDateTime.parse(trimmed, INPUT_WITH_TIME);
        } catch (DateTimeParseException e) {
            // Not a date with a time. It may still be a date on its own.
        }

        try {
            return LocalDate.parse(trimmed, INPUT_DATE_ONLY).atTime(defaultTime);
        } catch (DateTimeParseException e) {
            throw new DateFormatException(trimmed);
        }
    }

    /**
     * Stores a task and prints the confirmation shared by all three add
     * commands, including the running total.
     *
     * @param task the task that was just built
     * @throws TaskSaveException if the new list cannot be written, in which
     *                           case the task is taken out again
     */
    private static void addAndConfirm(Task task) throws TaskSaveException {
        tasks.add(task);
        try {
            storage.save(tasks);
        } catch (TaskSaveException e) {
            tasks.remove(tasks.size() - 1);
            throw e;
        }
        ui.show("Got it. I've added this task:\n  " + task
                + "\nNow you have " + tasks.size()
                + (tasks.size() == 1 ? " task" : " tasks") + " in the list.");
    }

    /**
     * Creates a todo from the rest of the command and stores it.
     *
     * @param details the command text after {@code todo}, the description
     */
    /**
     * Creates a todo from the rest of the command and stores it.
     *
     * @param details the command text after {@code todo}, the description
     * @throws TodoFormatException if no description was given
     * @throws TaskSaveException if the new list cannot be written
     */
    private static void addTodo(String details)
            throws TodoFormatException, TaskSaveException {
        String description = details.trim();
        if (description.isEmpty()) {
            throw new TodoFormatException();
        }
        addAndConfirm(new Todo(description));
    }

    /**
     * Creates a deadline from the rest of the command and stores it.
     *
     * @param details the command text after {@code deadline}, in the form
     *                {@code description /by when}
     * @throws DeadlineFormatException if the description or the /by part is missing
     * @throws DateFormatException if the /by part is not a date
     * @throws TaskSaveException if the new list cannot be written
     */
    private static void addDeadline(String details)
            throws DeadlineFormatException, DateFormatException, TaskSaveException {
        String[] descriptionAndBy = details.split(" /by ", 2);
        if (descriptionAndBy.length < 2) {
            throw new DeadlineFormatException();
        }

        String description = descriptionAndBy[0].trim();
        String by = descriptionAndBy[1].trim();
        if (description.isEmpty() || by.isEmpty()) {
            throw new DeadlineFormatException();
        }
        addAndConfirm(new Deadline(description,
                parseDateTime(by, DEADLINE_DEFAULT_TIME)));
    }

    /**
     * Creates an event from the rest of the command and stores it.
     *
     * @param details the command text after {@code event}, in the form
     *                {@code description /from start /to end}
     * @throws EventFormatException if the description, /from or /to part is missing
     * @throws DateFormatException if the /from or /to part is not a date
     * @throws TaskSaveException if the new list cannot be written
     */
    private static void addEvent(String details)
            throws EventFormatException, DateFormatException, TaskSaveException {
        String[] descriptionAndTimes = details.split(" /from ", 2);
        if (descriptionAndTimes.length < 2) {
            throw new EventFormatException();
        }

        String[] fromAndTo = descriptionAndTimes[1].split(" /to ", 2);
        if (fromAndTo.length < 2) {
            throw new EventFormatException();
        }

        String description = descriptionAndTimes[0].trim();
        String from = fromAndTo[0].trim();
        String to = fromAndTo[1].trim();
        if (description.isEmpty() || from.isEmpty() || to.isEmpty()) {
            throw new EventFormatException();
        }
        LocalDateTime start = parseDateTime(from, DEADLINE_DEFAULT_TIME);
        LocalDateTime end = parseDateTime(to, EVENT_END_DEFAULT_TIME);
        // An event that ends before it starts was only checkable once the times
        // became real dates. An event that starts and ends at the same moment
        // is allowed; it is odd, not wrong.
        if (end.isBefore(start)) {
            throw new EventFormatException(start, end);
        }
        addAndConfirm(new Event(description, start, end));
    }

    /** Prints every stored task, numbered from 1. */
    private static void listTasks() {
        if (tasks.isEmpty()) {
            ui.show("Nothing on the agenda yet.");
            return;
        }

        StringBuilder list = new StringBuilder();
        for (int i = 0; i < tasks.size(); i++) {
            // Tasks are numbered from 1 for the user, but indexed from 0 here.
            // Task.toString() supplies the "[X] " or "[ ] " status box.
            list.append(i + 1).append(".").append(tasks.get(i));
            if (i < tasks.size() - 1) {
                list.append("\n");
            }
        }
        ui.show(list.toString());
    }
    /**
     * Reads the task number the user typed and returns the task it points at.
     *
     * @param number the text the user gave after {@code mark} or {@code unmark}
     * @return the task at that position
     * @throws TaskNumberFormatException if the text is not a readable number
     * @throws OutOfBoundException if no task sits at that position
     */
    private static Task taskAt(String number)
            throws TaskNumberFormatException, OutOfBoundException {
        String text = number.trim();
        int index;
        try {
            index = Integer.parseInt(text);
        } catch (NumberFormatException e) {
            throw new TaskNumberFormatException(text);
        }

        if (index < 1 || index > tasks.size()) {
            throw new OutOfBoundException(index, tasks.size());
        }
        // The user counts from 1, the list indexes from 0.
        return tasks.get(index - 1);
    }

    /**
     * Marks the task the user named as done, then confirms it.
     *
     * @param number the text the user gave after {@code mark}
     * @throws TaskNumberFormatException if the text is not a readable number
     * @throws OutOfBoundException if no task sits at that position
     * @throws TaskSaveException if the change cannot be written, in which case
     *                           it is undone
     */
    private static void mark(String number)
            throws TaskNumberFormatException, OutOfBoundException, TaskSaveException {
        Task task = taskAt(number);
        // The task may already be done, so the undo restores what was there
        // before rather than assuming it was not done.
        boolean wasMarked = task.isMarked();
        task.mark();
        try {
            storage.save(tasks);
        } catch (TaskSaveException e) {
            if (!wasMarked) {
                task.unmark();
            }
            throw e;
        }
        ui.show("Nice! I've marked this task as done:\n  " + task);
    }

    /**
     * Marks the task the user named as not done, then confirms it.
     *
     * @param number the text the user gave after {@code unmark}
     * @throws TaskNumberFormatException if the text is not a readable number
     * @throws OutOfBoundException if no task sits at that position
     * @throws TaskSaveException if the change cannot be written, in which case
     *                           it is undone
     */
    private static void unmark(String number)
            throws TaskNumberFormatException, OutOfBoundException, TaskSaveException {
        Task task = taskAt(number);
        boolean wasMarked = task.isMarked();
        task.unmark();
        try {
            storage.save(tasks);
        } catch (TaskSaveException e) {
            if (wasMarked) {
                task.mark();
            }
            throw e;
        }
        ui.show("OK, I've marked this task as not done yet:\n  " + task);
    }

    /**
     * Deletes the task the user named.
     *
     * @param number the text the user gave after {@code delete}
     * @throws TaskNumberFormatException if the text is not a readable number
     * @throws OutOfBoundException if no task sits at that position
     * @throws TaskSaveException if the shorter list cannot be written, in which
     *                           case the task is put back where it was
     */
    private static void deleteTask(String number)
            throws TaskNumberFormatException, OutOfBoundException, TaskSaveException {
        Task task = taskAt(number);
        int position = tasks.indexOf(task);
        tasks.remove(position);
        try {
            storage.save(tasks);
        } catch (TaskSaveException e) {
            tasks.add(position, task);
            throw e;
        }
        ui.show("Noted. I've removed this task:\n  " + task
                + "\nNow you have " + tasks.size() + " task(s) in the list.");
    }


    /**
     * Carries out one line of input from the user.
     * <p>
     * The loop in {@link #main} reads lines; this method decides what a line
     * means and does it. Anything the user got wrong leaves here as a
     * {@link GudGoiException} for the caller to report.
     *
     * @param line one line the user typed, already trimmed
     * @throws GudGoiException if the command or its arguments are unusable
     */
    private static void handle(String line) throws GudGoiException {
        String[] parts = line.split(" ", 2);
        String cmd = parts[0];
        String rest = parts.length > 1 ? parts[1] : "";

        switch (cmd) {
        case "list" -> listTasks();
        case "mark" -> mark(rest);
        case "unmark" -> unmark(rest);
        case "todo" -> addTodo(rest);
        case "deadline" -> addDeadline(rest);
        case "event" -> addEvent(rest);
        case "delete" -> deleteTask(rest);
        default -> throw new CommandNotFoundException();
        }
    }

    /**
     * Starts the bot: greets the user, restores the saved agenda, then reads
     * and carries out commands until {@code bye} or the end of input.
     *
     * @param args ignored; the bot takes no command line arguments
     */
    public static void main(String[] args) {
        ui.showBanner();
        ui.showGreeting();

        try {
            tasks.addAll(storage.load());
        } catch (TaskLoadException e) {
            // A missing or damaged file costs the old agenda, not the session.
            ui.showError(e.getMessage());
        }

        String line;
        while (!(line = ui.readCommand()).equals("bye")) {
            try {
                handle(line);
            } catch (GudGoiException e) {
                ui.showError(e.getMessage());
            }
        }

        ui.showFarewell();
    }
}
